#!/usr/bin/env bash
# One-time (and safe to re-run) setup: Swarm, network, secrets file, registry, Portainer.
# Runs automatically every time the Codespace starts.
source "$(dirname "$0")/lib.sh"

wait_for_docker

step "Docker Swarm"
if [[ "$(docker info --format '{{.Swarm.LocalNodeState}}')" != "active" ]]; then
  docker swarm init >/dev/null
  echo "Swarm initialised. This machine is now a manager node."
else
  echo "Swarm already active."
fi

step "Overlay network 'labnet'"
if ! docker network inspect labnet >/dev/null 2>&1; then
  docker network create --driver overlay --attachable labnet >/dev/null
  echo "Created."
else
  echo "Already exists."
fi

step "Secrets file infra/.env"
if [[ ! -f "$ROOT/infra/.env" ]]; then
  # Upper case + lower case + digits, as SQL Server's password policy requires.
  sa="Lab$(openssl rand -hex 10)Aa9"
  minio="Lab$(openssl rand -hex 10)Aa9"
  kc="Lab$(openssl rand -hex 10)Aa9"
  cs() { echo "Server=sqlserver,1433;Database=$1;User Id=sa;Password=$sa;TrustServerCertificate=True"; }
  cat > "$ROOT/infra/.env" <<EOF
# Generated by scripts/bootstrap.sh. NOT committed to Git (see .gitignore).
MSSQL_SA_PASSWORD=$sa
MINIO_ROOT_USER=labadmin
MINIO_ROOT_PASSWORD=$minio
KC_BOOTSTRAP_ADMIN_USERNAME=admin
KC_BOOTSTRAP_ADMIN_PASSWORD=$kc
ConnectionStrings__Sales=$(cs SalesDb)
ConnectionStrings__Customers=$(cs CustomersDb)
ConnectionStrings__Documents=$(cs DocumentsDb)
Minio__AccessKey=labadmin
Minio__SecretKey=$minio
EOF
  echo "Generated with random passwords. Read them with: cat infra/.env"
else
  echo "Already exists (kept)."
fi

step "Image registry (stand-in for ACR) on :5000"
docker stack deploy -c "$ROOT/infra/registry.yml" registry >/dev/null
for _ in $(seq 1 30); do
  curl -fs "http://localhost:5000/v2/" >/dev/null 2>&1 && break
  sleep 2
done
curl -fs "http://localhost:5000/v2/" >/dev/null && echo "Registry is up." || echo "Registry not answering yet; it may still be starting."

step "Portainer on :9443"
docker stack deploy -c "$ROOT/infra/portainer.yml" portainer >/dev/null
echo "Deployed. Open the 9443 port in the PORTS tab and create the admin user within 5 minutes."

step "Done"
if docker stack ls --format '{{.Name}}' | grep -qx "$STACK"; then
  echo "The '$STACK' stack is already deployed. Check it with: bash scripts/status.sh"
else
  echo "Next: bash scripts/build.sh all   then   bash scripts/deploy.sh"
fi
